#!/usr/bin/env python3
"""Export the displayed equations in a LaTeX document as transparent PNGs."""

import argparse
from dataclasses import dataclass
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

ALIGN = {"align", "alignat", "flalign", "gather", "eqnarray"}
DISPLAYS = ALIGN | {"equation", "multline", "displaymath"}
TOKENS = re.compile(
    r"(?P<comment>%[^\n]*)|(?P<verb>\\verb\*?(?P<delimiter>[^\w\s])[^\n]*?(?P=delimiter))"
    r"|\\(?P<env>begin|end)\s*\{(?P<name>[\w*]+)\}"
    r"|\\(?P<input>input|include)(?![A-Za-z@])\s*"
    r"(?:\{(?P<file>[^{}%]+)\}|(?P<bare>[^\s{}\\%]+))"
    r"|(?P<command>\\(?:[A-Za-z@]+|[^\n]))|(?P<char>[{}$])"
)
VERBATIM = {"verbatim", "verbatim*", "Verbatim", "lstlisting", "minted", "comment"}

# AMS display tags are generated by TeX after counters, subequations, and
# custom tags have been applied. Report them while a marked display is active.
NUMBER_HOOK = r"""
\makeatletter
\def\EquationPngId{}
\protected\def\EquationPngMark#1{%
  \ifmeasuring@\else
    \gdef\EquationPngId{#1}\typeout{EQPNG-SEEN:#1}%
  \fi}
\protected\def\EquationPngClear{\global\let\EquationPngId\@empty}
\def\EquationPngNumber#1{%
  \ifmeasuring@\else
    \ifx\EquationPngId\@empty\else
      \begingroup
      \let\ref\EquationPngRef
      \let\Hy@make@anchor\@empty
      \typeout{EQPNG-NUMBER:\EquationPngId:#1:END}%
      \endgroup
    \fi
  \fi}
\def\EquationPngRef#1{\getrefnumber{#1}}
\AddToHook{begindocument/end}{%
  \let\EquationPngTagForm\tagform@
  \def\tagform@#1{\EquationPngNumber{#1}\EquationPngTagForm{#1}}%
  \let\EquationPngMakeStarTag\make@df@tag@@
  \def\make@df@tag@@#1{%
    \EquationPngMakeStarTag{#1}%
    \begingroup
    \toks@{\EquationPngNumber{#1}}%
    \toks\tw@=\expandafter{\df@tag}%
    \xdef\df@tag{\the\toks@\the\toks\tw@}%
    \endgroup}%
  \let\EquationPngEqref\eqref
  \protected\def\eqref#1{%
    \begingroup\let\EquationPngId\@empty\EquationPngEqref{#1}\endgroup}%
}
\makeatother
"""

# These affect the original display or its tag, rather than the isolated math.
REMOVE_COMMANDS = {
    r"\label", r"\tag", r"\notag", r"\nonumber", r"\numberthis",
    r"\intertext", r"\shortintertext", r"\displaybreak", r"\raisetag",
    r"\shoveleft", r"\shoveright",
}


@dataclass
class Row:
    math: str
    labels: list[str]
    marker: int = 0


@dataclass
class Display:
    rows: list[Row]
    separate_numbers: bool


def tokens(source: str, start: int = 0):
    """Yield TeX tokens of interest, skipping comments and verbatim contents."""
    while match := TOKENS.search(source, start):
        start = match.end()
        if match["env"] == "begin" and match["name"] in VERBATIM:
            end = re.search(
                r"\\end\s*\{" + re.escape(match["name"]) + r"\}", source[start:]
            )
            start += end.end() if end else len(source) - start
        elif match["comment"] is None and match["verb"] is None:
            yield match


def group_end(source: str, start: int, opening: str, closing: str) -> int:
    """Read a balanced argument, honoring escaped braces and comments."""
    depth = 0
    pattern = re.compile(r"\\[^\n]|%[^\n]*|" + re.escape(opening) + "|" + re.escape(closing))
    for match in pattern.finditer(source, start):
        if match[0] == opening:
            depth += 1
        elif match[0] == closing:
            depth -= 1
            if not depth:
                return match.end()
    raise ValueError(f"Unclosed {opening} argument")


def rows_in(source: str, split_rows: bool):
    """Find row spans at the top level of a display."""
    depth = nested = start = skip_to = 0
    for token in tokens(source):
        if token.start() < skip_to:
            continue
        if token["env"]:
            nested += 1 if token["env"] == "begin" else -1
        elif token[0] == "{":
            depth += 1
        elif token[0] == "}":
            depth -= 1
        elif split_rows and not (depth or nested) and token[0] in {r"\\", r"\cr"}:
            yield start, token.start()
            separator = re.match(r"\*?(?:\s*\[)?", source[token.end():])
            start = token.end() + separator.end()
            if separator[0].endswith("["):
                start = group_end(source, start - 1, "[", "]")
            skip_to = start
    yield start, len(source)


def clean_row(source: str) -> Row:
    parts = []
    labels = []
    previous = 0
    for token in tokens(source):
        if token.start() < previous:
            continue
        command = token["command"]
        if command not in REMOVE_COMMANDS and not (
            token["env"] and token["name"] == "split"
        ):
            continue
        parts.append(source[previous:token.start()])
        previous = token.end()
        if token["env"]:
            parts.append(r"\begin{aligned}" if token["env"] == "begin" else r"\end{aligned}")
        elif command in {r"\label", r"\tag", r"\intertext", r"\shortintertext", r"\raisetag"}:
            argument = re.match(r"\s*\*?\s*\{", source[previous:])
            if argument:
                opening = previous + argument.end() - 1
                previous = group_end(source, opening, "{", "}")
                if command == r"\label":
                    labels.append(source[opening + 1:previous - 1].strip())
        elif command == r"\displaybreak":
            argument = re.match(r"\s*\[", source[previous:])
            if argument:
                previous = group_end(source, previous + argument.end() - 1, "[", "]")
    parts.append(source[previous:])
    return Row(re.sub(r"(?m)^[ \t]*\n", "", "".join(parts)), labels)


def row_marker_offset(source: str) -> int:
    # Intertext expands to \noalign, which must precede material in the row.
    offset = 0
    while match := re.match(
        r"(?:\s|%[^\n]*\n)*\\(?:shortintertext|intertext)\s*\{", source[offset:]
    ):
        offset = group_end(source, offset + match.end() - 1, "{", "}")
    return offset


def edit_source(source: str, edits: list[tuple[int, int, str]]) -> str:
    parts = []
    previous = 0
    for start, end, replacement in sorted(edits, key=lambda edit: edit[0]):
        parts.extend((source[previous:start], replacement))
        previous = end
    parts.append(source[previous:])
    return "".join(parts)


class Document:
    def __init__(self, source: Path, build: Path):
        self.source = source
        self.build = build
        self.displays: list[Display] = []
        self.marker_count = 0
        self.active_files: set[Path] = set()
        text = source.read_text(encoding="utf-8")
        begin = next(
            (token for token in tokens(text) if token["env"] == "begin" and token["name"] == "document"),
            None,
        )
        if begin is None:
            raise ValueError("Pass the main .tex file containing \\begin{document}.")
        self.preamble = text[:begin.start()]
        numbered_preamble = self.preamble + "\n" + r"\RequirePackage{amsmath,refcount}" + NUMBER_HOOK
        (build / "numbered.tex").write_text(
            numbered_preamble + self.instrument(text[begin.start():], source), encoding="utf-8"
        )

    def marker(self) -> int:
        self.marker_count += 1
        return self.marker_count

    def instrument(self, text: str, path: Path) -> str:
        if path in self.active_files:
            raise ValueError(f"Circular LaTeX input involving {path}")
        self.active_files.add(path)
        edits = []
        pending = None
        inline_dollar = False
        skip_to = 0
        for token in tokens(text):
            if token.start() < skip_to:
                continue
            if pending:
                opening, closing, name = pending
                if (
                    token[0] == closing
                    or (token["env"] == "end" and token["name"] == closing)
                    or (
                        closing == "$$"
                        and token[0] == "$"
                        and text.startswith("$$", token.start())
                    )
                ):
                    end = token.start() + 2 if closing == "$$" else token.end()
                    self.add_display(text, opening, token.start(), end, name, edits)
                    pending = None
                    skip_to = end
                continue
            if token["env"] == "end" and token["name"] == "document":
                break
            if token["input"]:
                edits.append(self.instrument_input(token))
            elif token["env"] == "begin" and token["name"].rstrip("*") in DISPLAYS:
                pending = token, token["name"], token["name"].rstrip("*")
            elif token[0] == r"\[":
                pending = token, r"\]", "displaymath"
            elif token[0] == "$":
                if not inline_dollar and text.startswith("$$", token.start()):
                    pending = token, "$$", "displaymath"
                    skip_to = token.end() + 1
                else:
                    inline_dollar = not inline_dollar
        if pending:
            raise ValueError(f"Unclosed {pending[2]} display in {path}")
        self.active_files.remove(path)
        return edit_source(text, edits)

    def instrument_input(self, token: re.Match) -> tuple[int, int, str]:
        name = (token["file"] or token["bare"]).strip()
        relative = Path(name if name.endswith(".tex") else name + ".tex")
        source = self.source.parent / relative
        if not source.is_file():
            return token.start(), token.end(), token[0]
        if token["input"] == "include" and not relative.is_absolute() and ".." not in relative.parts:
            # Preserve the name used by \includeonly and the chapter's checkpoint.
            target = self.build / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(
                self.instrument(source.read_text(encoding="utf-8"), source.resolve()),
                encoding="utf-8",
            )
            return token.start(), token.end(), token[0]
        # Each occurrence gets its own markers, even when a file is input twice.
        with tempfile.NamedTemporaryFile(dir=self.build, prefix="section-", suffix=".tex") as item:
            target = Path(item.name)
        target.write_text(
            self.instrument(source.read_text(encoding="utf-8"), source.resolve()), encoding="utf-8"
        )
        return token.start(), token.end(), rf'\{token["input"]}{{{target.stem}}}'

    def add_display(self, text, opening, body_end, end, name, edits):
        body_start = opening.end() + (1 if opening[0] == "$" else 0)
        if name == "alignat":
            columns = re.match(r"\s*\{\s*\d+\s*\}", text[body_start:body_end])
            if columns:
                body_start += columns.end()
        body = text[body_start:body_end]
        separate_numbers = name in ALIGN
        row_spans = rows_in(body, separate_numbers or name == "multline")
        shared_marker = 0 if separate_numbers else self.marker()
        if shared_marker:
            edits.append((opening.start(), opening.start(), rf"\EquationPngMark{{{shared_marker}}}"))
        rows = []
        for start, stop in row_spans:
            row_source = body[start:stop]
            row = clean_row(row_source)
            visible_source = TOKENS.sub(
                lambda token: "" if token["comment"] is not None else token[0], row.math
            )
            if not visible_source.strip():
                continue
            row.marker = shared_marker or self.marker()
            rows.append(row)
            if separate_numbers:
                offset = body_start + start + row_marker_offset(row_source)
                edits.append((offset, offset, rf"\EquationPngMark{{{row.marker}}}"))
        edits.append((end, end, r"\EquationPngClear{}"))
        self.displays.append(Display(rows, separate_numbers))


def run(command: list[str], build: Path, env: dict[str, str]) -> str:
    result = subprocess.run(command, cwd=build, env=env, text=True,
                            encoding="utf-8", errors="replace",
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if result.returncode:
        excerpt = "\n".join(result.stdout.splitlines()[-35:])
        raise ValueError(f"{command[0]} failed.\n{excerpt}")
    return result.stdout


def groups_for(display: Display, seen: set[int], numbers: dict[int, str]):
    rows = [row for row in display.rows if row.marker in seen]
    if not rows:
        return []
    if not display.separate_numbers:
        return [(numbers.get(rows[0].marker), rows)]
    # An untagged row belongs to the next tagged row, or to the last tag
    # in the display if the untagged row trails it.
    groups = []
    pending = []
    for row in rows:
        pending.append(row)
        if row.marker in numbers:
            groups.append((numbers[row.marker], pending))
            pending = []
    if pending:
        if groups:
            groups[-1][1].extend(pending)
        else:
            groups.append((None, pending))
    return groups


def filename_part(value: str) -> str:
    return re.sub(r"[^\w.+-]+", "-", value).strip(".-")[:100]


def names_and_rows(displays, seen, numbers):
    names = set()
    unnumbered = 0
    for display in displays:
        for number, rows in groups_for(display, seen, numbers):
            stem = filename_part(number or "")
            if not stem:
                unnumbered += 1
                stem = f"unnumbered-{unnumbered:03}"
            label = next(
                (label for row in rows if row.marker in numbers for label in row.labels if label),
                "",
            ) or next((label for row in rows for label in row.labels if label), "")
            if safe_label := filename_part(label):
                stem += f"_{safe_label}"
            for index, row in enumerate(rows, 1):
                base = f"{stem}_line-{index:02}" if len(rows) > 1 else stem
                name = base + ".png"
                suffix = 2
                while name.casefold() in names:
                    name = f"{base}_{suffix}.png"
                    suffix += 1
                names.add(name.casefold())
                yield name, row, display.separate_numbers


def render_source(preamble, images, color):
    if re.fullmatch(r"#?[0-9a-fA-F]{6}", color):
        setup = rf"\definecolor{{EquationPngColor}}{{HTML}}{{{color.lstrip('#').upper()}}}"
    elif re.fullmatch(r"[A-Za-z][A-Za-z0-9-]*", color):
        setup = rf"\colorlet{{EquationPngColor}}{{{color}}}"
    else:
        raise ValueError("Use an xcolor name or a six-digit hex color, such as '#3264B0'.")
    lines = [
        preamble,
        r"\RequirePackage{amsmath,xcolor}",
        r"\RequirePackage[active,tightpage]{preview}",
        r"\setlength\PreviewBorder{2pt}",
        setup,
        r"\begin{document}",
    ]
    for _, row, aligned in images:
        math = row.math.strip()
        if aligned:
            math = "\\begin{aligned}\n" + math + "\n\\end{aligned}"
        lines.extend((
            r"\begin{preview}\color{EquationPngColor}\(\displaystyle",
            math,
            r"\)\end{preview}",
        ))
    lines.append(r"\end{document}")
    return "\n".join(lines)


def export(source: Path, output: Path, color: str, dpi: int) -> int:
    resolved = output.resolve()
    if any(part.casefold() == "paper-drafts" for part in (*output.parts, *resolved.parts)):
        raise ValueError("Choose an output folder outside Paper-Drafts.")
    output = resolved
    for executable in ("pdflatex", "pdftocairo"):
        if not shutil.which(executable):
            raise ValueError(f"Required command {executable} was not found on PATH.")

    with tempfile.TemporaryDirectory(prefix="equation-png-") as temporary:
        build = Path(temporary)
        document = Document(source, build)
        env = os.environ.copy()
        env["TEXINPUTS"] = os.pathsep.join((".", str(source.parent), env.get("TEXINPUTS", "")))
        latex = ["pdflatex", "-no-shell-escape", "-interaction=nonstopmode",
                 "-halt-on-error", "-file-line-error", "-jobname=article"]
        run(latex + ["numbered.tex"], build, env)
        log = run(latex + ["numbered.tex"], build, env)
        seen = {int(marker) for marker in re.findall(r"^EQPNG-SEEN:(\d+)$", log, re.MULTILINE)}
        numbers = {
            int(marker): number
            for marker, number in re.findall(r"^EQPNG-NUMBER:(\d+):(.*?):END$", log, re.MULTILINE)
        }
        images = list(names_and_rows(document.displays, seen, numbers))
        if not images:
            return 0

        (build / "render.tex").write_text(
            render_source(document.preamble, images, color), encoding="utf-8"
        )
        run(latex + ["render.tex"], build, env)
        run(["pdftocairo", "-png", "-transp", "-r", str(dpi), "article.pdf", "page"],
            build, env)
        pages = sorted(build.glob("page-*.png"), key=lambda page: int(page.stem.split("-")[-1]))
        if len(pages) != len(images):
            raise ValueError(f"Expected {len(images)} rendered pages, got {len(pages)}.")

        output.mkdir(parents=True, exist_ok=True)
        for page, (name, _, _) in zip(pages, images):
            with tempfile.NamedTemporaryFile(dir=output, prefix=".equation-", delete=False) as item:
                staged = Path(item.name)
            try:
                shutil.copyfile(page, staged)
                staged.replace(output / name)
            finally:
                staged.unlink(missing_ok=True)
    return len(images)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tex", type=Path, help="main .tex file, including its preamble")
    parser.add_argument("output", type=Path, help="destination folder for the PNGs")
    parser.add_argument("--color", default="black", help="xcolor name or '#RRGGBB' (default: black)")
    parser.add_argument("--dpi", default=600, type=int, help="raster resolution (default: 600)")
    args = parser.parse_args()
    if args.dpi < 1:
        parser.error("--dpi must be positive")
    try:
        count = export(args.tex.resolve(strict=True), args.output, args.color, args.dpi)
    except (OSError, ValueError) as error:
        parser.exit(1, f"{error}\n")
    print(f"Exported {count} equation PNGs to {args.output.resolve()}")


if __name__ == "__main__":
    main()
